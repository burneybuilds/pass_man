alpha = {
"a": "@", "b": "7", "c": "#", "d": "m", "e": "$",
"f": "2", "g": "&", "h": "Q", "i": "!", "j": "9",
"k": "%", "l": "x", "m": "*", "n": "A", "o": "+",
"p": "5", "q": "?", "r": "L", "s": "^", "t": "0",
"u": "Z", "v": "(", "w": "}", "x": "8", "y": "~", "z": "]"
}
numbers = {
"0": "b", "1": "C", "2": "=", "3": "d", "4": "|",
"5": "E", "6": "/", "7": "f", "8": ":", "9": "G"
}
caps = {
"A": "h", "B": "I", "C": "j", "D": "K", "E": "l",
"F": "M", "G": "n", "H": "O", "I": "p", "J": "R",
"K": "s", "L": "T", "M": "u", "N": "V", "O": "w",
"P": "X", "Q": "y", "R": "Y", "S": "z", "T": "B",
"U": "c", "V": "D", "W": "e", "X": "F", "Y": "g",
"Z": "H"
}
symbols = {
"`": "¢", "~": "£", "!": "¥", "@": "§", "#": "©",
"$": "®", "%": "±", "^": "×", "&": "÷", "*": "µ",
"(": "¶", ")": "°", "-": "¤", "_": "¿", "=": "¡",
"+": "¬", "[": "¯", "]": "¦", "{": "¨", "}": "ª",
"\\": "º", "|": "«", ";": "»", ":": "¸", "'": "¼",
"\"": "½", ",": "¾", ".": "¹", "<": "²", ">": "³",
"/": "´", "?": "·"
}

mapping = alpha | numbers | caps | symbols


def decode(encoded_text):
    reverse_mapping = {v: k for k, v in mapping.items()}

    decoded = ""

    for char in encoded_text:
        decoded += reverse_mapping.get(char, char)

    return decoded